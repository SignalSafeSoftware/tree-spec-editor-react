import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { createServer } from "vite";
import { chromium } from "playwright";

const require = createRequire(import.meta.url);
const demoRoot = new URL("./", import.meta.url);
const outputPath = new URL("../tree-spec-example-flow.svg", import.meta.url);
const demoStylesPath = new URL("./editor-demo.css", import.meta.url);
const reactFlowStylesPath = require.resolve("reactflow/dist/style.css");
const checkOnly = process.argv.includes("--check");

const width = 1400;
const height = 840;

function escapeXml(value) {
    return value
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;");
}

async function readGeneratedStyles() {
    const [reactFlowStyles, demoStyles] = await Promise.all(
        [reactFlowStylesPath, demoStylesPath].map((path) => readFile(path, "utf8")),
    );

    return `${reactFlowStyles.trimEnd()}\n${demoStyles.trimEnd()}`;
}

function buildSvg(markup, styles) {
    const markupWithSvgNamespaces = markup.replace(
        /<svg (?!xmlns=)/g,
        '<svg xmlns="http://www.w3.org/2000/svg" ',
    );
    return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by docs/demo/generate-doc-images.mjs. Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <title>TreeSpec editor incident response example</title>
  <foreignObject x="0" y="0" width="${width}" height="${height}">
    <div xmlns="http://www.w3.org/1999/xhtml">
      <style>${escapeXml(styles)}</style>
      ${markupWithSvgNamespaces}
    </div>
  </foreignObject>
</svg>
`;
}

async function main() {
    const server = await createServer({
        root: demoRoot.pathname,
        configFile: false,
        server: { host: "127.0.0.1", port: 0 },
        optimizeDeps: { force: true },
    });

    await server.listen();
    const address = server.httpServer?.address();
    if (!address || typeof address === "string") {
        await server.close();
        throw new Error("Vite did not expose a local HTTP address");
    }

    const browser = await chromium.launch({ headless: true });
    try {
        const page = await browser.newPage({ viewport: { width, height } });
        await page.goto(`http://127.0.0.1:${address.port}/`, { waitUntil: "networkidle" });
        await page.waitForFunction(
            () =>
                document.querySelectorAll(".react-flow__node .graph-editor-canvas-node").length === 4 &&
                document.querySelector('.react-flow__node[data-id="END"] .graph-editor-canvas-node'),
        );
        await page.waitForTimeout(150);

        const markup = await page.locator("#editor-preview").evaluate((element) => element.outerHTML);
        const styles = await readGeneratedStyles();
        const svg = buildSvg(markup, styles);

        if (checkOnly) {
            const existing = await readFile(outputPath, "utf8");
            if (existing !== svg) {
                throw new Error("docs/tree-spec-example-flow.svg is stale; run yarn docs:images");
            }
        } else {
            await mkdir(new URL("../", import.meta.url), { recursive: true });
            await writeFile(outputPath, svg, "utf8");
        }
    } finally {
        await browser.close();
        await server.close();
    }
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
