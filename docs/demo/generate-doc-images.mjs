import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { createServer } from "vite";
import { chromium } from "playwright";

const require = createRequire(import.meta.url);
const demoRoot = new URL("./", import.meta.url);
const outputPath = new URL("../tree-spec-example-flow.svg", import.meta.url);
const demoStylesPath = new URL("./editor-demo.css", import.meta.url);
const distributionRoot = new URL("../../dist/", demoRoot);
const reactFlowStylesPath = require.resolve("reactflow/dist/style.css");
const checkOnly = process.argv.includes("--check");

const width = 1400;
const height = 840;
const expectedSvgFragments = [
    '<main class="docs-preview" id="editor-preview">',
    'data-id="triage"',
    'data-id="investigate"',
    'data-id="recovery"',
    'data-id="END"',
];

function escapeXml(value) {
    return value
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;");
}

async function readGeneratedStyles() {
    const [reactFlowStyles, demoStyles] = await Promise.all(
        [reactFlowStylesPath, demoStylesPath].map((path) => readFile(path, "utf8")),
    );

    return `${reactFlowStyles.trimEnd()}\n${demoStyles.trimEnd()}`;
}

async function listJavaScriptFiles(directoryUrl) {
    const entries = await readdir(directoryUrl, { withFileTypes: true });
    const nestedFiles = await Promise.all(
        entries
            .sort((left, right) => left.name.localeCompare(right.name))
            .map(async (entry) => {
                const entryUrl = new URL(entry.name, directoryUrl);
                if (entry.isDirectory()) {
                    return listJavaScriptFiles(new URL(`${entry.name}/`, directoryUrl));
                }

                return entry.isFile() && entry.name.endsWith(".js") ? [entryUrl] : [];
            }),
    );

    return nestedFiles.flat();
}

async function getSourceFingerprint() {
    const distributionFiles = await listJavaScriptFiles(distributionRoot);
    const inputs = [
        { id: "docs/demo/editor-demo.css", path: demoStylesPath },
        { id: "docs/demo/generate-doc-images.mjs", path: new URL("./generate-doc-images.mjs", demoRoot) },
        { id: "docs/demo/index.html", path: new URL("./index.html", demoRoot) },
        { id: "docs/demo/main.jsx", path: new URL("./main.jsx", demoRoot) },
        { id: "docs/demo/treeSpecExample.mjs", path: new URL("./treeSpecExample.mjs", demoRoot) },
        { id: "node_modules/reactflow/dist/style.css", path: reactFlowStylesPath },
        { id: "package.json", path: new URL("../../package.json", demoRoot) },
        { id: "yarn.lock", path: new URL("../../yarn.lock", demoRoot) },
        ...distributionFiles.map((path) => ({
            id: `dist/${path.pathname.slice(distributionRoot.pathname.length)}`,
            path,
        })),
    ].sort((left, right) => left.id.localeCompare(right.id));
    const hash = createHash("sha256");

    for (const input of inputs) {
        hash.update(input.id);
        hash.update("\0");
        hash.update(await readFile(input.path));
        hash.update("\0");
    }

    return hash.digest("hex");
}

function buildSvg(markup, styles, sourceFingerprint) {
    const markupWithSvgNamespaces = markup.replace(
        /<svg (?!xmlns=)/g,
        '<svg xmlns="http://www.w3.org/2000/svg" ',
    );
    return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by docs/demo/generate-doc-images.mjs. Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" data-tree-spec-demo-source-hash="${sourceFingerprint}">
  <title>TreeSpec editor incident response example</title>
  <foreignObject x="0" y="0" width="${width}" height="${height}">
    <div xmlns="http://www.w3.org/1999/xhtml">
      <style>${escapeXml(styles)}</style>
      ${markupWithSvgNamespaces}
    </div>
  </foreignObject>
</svg>
`;
}

async function verifyGeneratedImage(sourceFingerprint) {
    const existing = await readFile(outputPath, "utf8");
    const hasCurrentSources = existing.includes(`data-tree-spec-demo-source-hash="${sourceFingerprint}"`);
    const hasExpectedStructure = expectedSvgFragments.every((fragment) => existing.includes(fragment));

    if (!hasCurrentSources || !hasExpectedStructure) {
        throw new Error("docs/tree-spec-example-flow.svg is stale; run yarn docs:images");
    }
}

async function main() {
    const server = await createServer({
        root: demoRoot.pathname,
        configFile: false,
        server: { host: "127.0.0.1", port: 0 },
        optimizeDeps: { force: true },
    });

    await server.listen();
    const address = server.httpServer?.address();
    if (!address || typeof address === "string") {
        await server.close();
        throw new Error("Vite did not expose a local HTTP address");
    }

    const browser = await chromium.launch({ headless: true });
    try {
        const page = await browser.newPage({ viewport: { width, height } });
        await page.goto(`http://127.0.0.1:${address.port}/`, { waitUntil: "networkidle" });
        await page.waitForFunction(
            () =>
                document.querySelectorAll(".react-flow__node .graph-editor-canvas-node").length === 4 &&
                document.querySelector('.react-flow__node[data-id="END"] .graph-editor-canvas-node'),
        );
        await page.waitForTimeout(150);

        const sourceFingerprint = await getSourceFingerprint();

        if (checkOnly) {
            await verifyGeneratedImage(sourceFingerprint);
        } else {
            const markup = await page.locator("#editor-preview").evaluate((element) => element.outerHTML);
            const styles = await readGeneratedStyles();
            const svg = buildSvg(markup, styles, sourceFingerprint);
            await mkdir(new URL("../", import.meta.url), { recursive: true });
            await writeFile(outputPath, svg, "utf8");
        }
    } finally {
        await browser.close();
        await server.close();
    }
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
